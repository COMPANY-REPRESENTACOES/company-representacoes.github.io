-- Company Vendas · cadastro de transportadoras
create table if not exists public.transportadoras (
  id uuid primary key default gen_random_uuid(),
  nome text not null,
  telefone text default '',
  telefone2 text default '',
  cidade text default '',
  uf text default '',
  criado_em timestamptz not null default now()
);
alter table public.transportadoras enable row level security;
drop policy if exists "transp todos" on public.transportadoras;
create policy "transp todos" on public.transportadoras for all to authenticated using (true) with check (true);
grant select, insert, update, delete on table public.transportadoras to authenticated;
grant select, insert, update, delete on table public.transportadoras to service_role;
